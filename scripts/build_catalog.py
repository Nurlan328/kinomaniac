QUERY = """
SELECT ?imdb (SAMPLE(?ru) AS ?title_ru) (SAMPLE(?en) AS ?title_en)
       (MIN(?date) AS ?first) (MIN(?dur) AS ?minutes)
       (GROUP_CONCAT(DISTINCT ?cl; separator="|") AS ?countries)
       (GROUP_CONCAT(DISTINCT ?ll; separator="|") AS ?languages)
       (GROUP_CONCAT(DISTINCT ?gl; separator="|") AS ?genres)
       (GROUP_CONCAT(DISTINCT ?tl; separator="|") AS ?types)
       (SAMPLE(?film) AS ?item)
WHERE {
  VALUES ?imdb { %s }
  ?film wdt:P345 ?imdb .
  ?film wdt:P31/wdt:P279* wd:Q11424 .
  OPTIONAL { ?film rdfs:label ?ru FILTER(LANG(?ru) = "ru") }
  OPTIONAL { ?film rdfs:label ?en FILTER(LANG(?en) = "en") }
  OPTIONAL { ?film wdt:P577 ?date }
  OPTIONAL { ?film wdt:P2047 ?dur }
  OPTIONAL { ?film wdt:P495 ?c . ?c rdfs:label ?cl FILTER(LANG(?cl) = "ru") }
  OPTIONAL { ?film wdt:P364 ?l . ?l rdfs:label ?ll FILTER(LANG(?ll) = "ru") }
  OPTIONAL { ?film wdt:P136 ?g . ?g rdfs:label ?gl FILTER(LANG(?gl) = "ru") }
  OPTIONAL { ?film wdt:P31 ?t . ?t rdfs:label ?tl FILTER(LANG(?tl) = "ru") }
}
GROUP BY ?imdb
"""


def fetch(imdb_ids):
    """Один SPARQL-запрос на весь список, ответ в виде словаря imdb → поля."""
    values = " ".join(f'"{x}"' for x in imdb_ids)
    url = ENDPOINT + "?" + urllib.parse.urlencode(
        {"query": QUERY % values, "format": "json"})
    request = urllib.request.Request(url, headers={"User-Agent": AGENT})
    with urllib.request.urlopen(request, timeout=120) as answer:
        rows = json.load(answer)["results"]["bindings"]
    out = {}
    for row in rows:
        get = lambda k: row.get(k, {}).get("value")  # noqa: E731
        out[get("imdb")] = {
            "title": get("title_ru") or get("title_en"),
            "title_en": get("title_en"),
            "year": int(get("first")[:4]) if get("first") else None,
            "minutes": int(float(get("minutes"))) if get("minutes") else None,
            "countries": [x for x in (get("countries") or "").split("|") if x],
            "languages": [x.replace(" язык", "") for x in (get("languages") or "").split("|") if x],
            "genres_raw": [x for x in (get("genres") or "").split("|") if x],
            "types": [x for x in (get("types") or "").split("|") if x],
            "item": get("item"),
        }
    return out


def short_genres(raw):
    """Жанры Wikidata → слова каталога; неизвестные печатаются и пропускаются."""
    result = []
    for name in raw:
        if name in SKIP:
            continue
        word = GENRES.get(name)
        if word is None:
            print(f"    неизвестный жанр: {name!r}")
            continue
        if word not in result:
            result.append(word)
    return result


def main():
    write = "--write" in sys.argv
    data = fetch(list(FILMS.values()))
    descriptions = json.loads((HERE / "descriptions.json").read_text("utf-8")) \
        if (HERE / "descriptions.json").exists() else {}
    films, problems = [], []
    for fid, imdb in FILMS.items():
        row = data.get(imdb)
        if row is None:
            problems.append(f"{fid} {imdb}: нет в Wikidata")
            continue
        genres = short_genres(row["genres_raw"])
        # Анимация в Wikidata это тип фильма (P31), а не жанр: добавляем «мультфильм».
        if any(re.search(r"анимац|мультфильм|аниме", t) for t in row["types"]) \
                and "мультфильм" not in genres:
            genres.insert(0, "мультфильм")
        print(f"{fid} {imdb} {row['title']!r} ({row['title_en']}) {row['year']} "
              f"{row['minutes']} мин | {row['countries']} | {row['languages']} "
              f"| {genres}")
        for field in ("title", "year", "minutes"):
            if not row[field]:
                problems.append(f"{fid}: нет поля {field}")
        if not row["countries"] or not row["languages"] or not genres:
            problems.append(f"{fid}: пустые страны, языки или жанры")
        if write and fid not in descriptions:
            problems.append(f"{fid}: нет описания в descriptions.json")
        films.append({
            "id": fid,
            "title": row["title"],
            "year": row["year"],
            "minutes": row["minutes"],
            "genres": genres,
            "countries": row["countries"],
            "languages": row["languages"],
            "description": descriptions.get(fid, ""),
            "source": f"https://www.wikidata.org/wiki/{row['item'].rsplit('/', 1)[-1]}"
                      f" (IMDb {imdb})",
        })
    kz_path = ROOT / "films_kz_example.json"
    if kz_path.exists():
        for film in json.loads(kz_path.read_text("utf-8")):
            films.append(film)
        print(f"+ {kz_path.name}: казахстанские фильмы из раздатки курса")
    print(f"\nФильмов: {len(films)}")
    for p in problems:
        print("ПРОБЛЕМА:", p)
    if write and not problems:
        (ROOT / "films.json").write_text(
            json.dumps(films, ensure_ascii=False, indent=2) + "\n", "utf-8")
        print("films.json записан")
    elif write:
        print("films.json не записан: есть проблемы")
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
